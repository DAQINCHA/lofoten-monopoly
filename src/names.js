// 从池子里挑一个房间内还没人用的名字；都占满了就加个后缀
export function pickName(usedNames = new Set()) {
  const pool = NAME_POOL.filter((n) => !usedNames.has(n));
  if (!pool.length) {
    const base = NAME_POOL[Math.floor(Math.random() * NAME_POOL.length)].slice(0, 10);
    let i = 2;
    while (usedNames.has(`${base}·${i}`) && i < 99) i++;
    return `${base}·${i}`;
  }
  return pool[Math.floor(Math.random() * pool.length)];
}
